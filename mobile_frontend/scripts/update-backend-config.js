const os = require('os');
const fs = require('fs');
const path = require('path');

function getLocalIp() {
  // 🚀 Priority 1: Use manual override URL if provided (crucial for --tunnel)
  if (process.env.BACKEND_URL) {
    return process.env.BACKEND_URL.trim();
  }
  // We can leave this fallback for local tests, but we will override it below.
  const interfaces = os.networkInterfaces();
  for (const name of Object.keys(interfaces)) {
    for (const iface of interfaces[name]) {
      if (iface.family === 'IPv4' && !iface.internal) {
        return iface.address;
      }
    }
  }
  return '127.0.0.1'; // Fallback
}

const ip = getLocalIp();
const configPath = path.join(__dirname, '..', 'constants', 'backend.ts');
const configDir = path.dirname(configPath);

if (!fs.existsSync(configDir)) {
  fs.mkdirSync(configDir, { recursive: true });
}

// Generate the backend config file
// AWS explicit override
const baseUrl = process.env.AWS_API_URL || 'https://u9zfrut1t9.execute-api.ap-south-1.amazonaws.com/dev';

// Determine WebSocket URL
// If an explicit AWS_WS_URL is provided, use it. Otherwise, fallback to deriving from baseUrl for local dev.
let wsUrl = '';
if (process.env.AWS_WS_URL) {
  wsUrl = process.env.AWS_WS_URL.trim();
} else {
  const wsPrefix = baseUrl.startsWith('https') ? 'wss://' : 'ws://';
  const host = baseUrl.replace(/^https?:\/\//, '');
  wsUrl = `${wsPrefix}${host}`;
}

console.log(`HTTP URL: ${baseUrl}`);
console.log(`WS URL: ${wsUrl}`);

const content = `// This file is auto-generated by scripts/update-backend-config.js.
// Do not edit it manually.
export const BACKEND_IP = '${ip}';
export const BACKEND_PORT = '8000';
export const API_BASE_URL = '${baseUrl}';
export const WS_BASE_URL = '${wsUrl}';
`;

fs.writeFileSync(configPath, content);
console.log(`✅ Backend HTTP configuration updated: ${baseUrl}`);
console.log(`✅ Backend WS configuration updated: ${wsUrl}`);
console.log(`📁 File updated: ${configPath}`);
